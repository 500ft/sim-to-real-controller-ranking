function S = fig_style()
%FIG_STYLE Shared figure rules for the MATLAB report figures.
%   Sets LaTeX text everywhere (Computer Modern), a three-size ladder (axis
%   labels and series labels 9 pt, notes 8 pt, tick labels 7 pt), panel
%   letters at 10 pt bold, outward ticks and no box. Returns the first two
%   MATLAB default line colours (blue, orange), ink for axes and text, grey
%   for reference lines and a light grey for shaded intervals.

S.size.label = 9;     % axis labels and direct series labels
S.size.note  = 8;     % annotations
S.size.tick  = 7;     % tick labels
S.size.letter = 10;   % panel letters (bold)

S.c.blue   = [0.0000 0.4470 0.7410];  % MATLAB default colour 1: reference, measured or passed
S.c.orange = [0.8500 0.3250 0.0980];  % MATLAB default colour 2: model, command or failed
S.c.ink    = [0.15 0.15 0.15];        % axes and text
S.c.grey   = [0.55 0.55 0.55];        % reference lines
S.c.stem   = [0.80 0.80 0.80];        % dot-plot stems
S.c.span   = [0.91 0.91 0.91];        % shaded intervals (held out, dropout, band)

S.width = 17.4;       % full report width (cm)

set(groot, ...
    'defaultTextInterpreter', 'latex', ...
    'defaultAxesTickLabelInterpreter', 'latex', ...
    'defaultLegendInterpreter', 'latex', ...
    'defaultColorbarTickLabelInterpreter', 'latex', ...
    'defaultAxesFontSize', S.size.tick, ...
    'defaultAxesLabelFontSizeMultiplier', S.size.label / S.size.tick, ...
    'defaultAxesTitleFontSizeMultiplier', S.size.label / S.size.tick, ...
    'defaultTextFontSize', S.size.note, ...
    'defaultAxesTickDir', 'out', ...
    'defaultAxesTickLength', [0.012 0.012], ...
    'defaultAxesBox', 'off', ...
    'defaultAxesLineWidth', 0.6, ...
    'defaultAxesXColor', S.c.ink, ...
    'defaultAxesYColor', S.c.ink, ...
    'defaultAxesColor', 'none', ...
    'defaultFigureColor', 'w', ...
    'defaultLineLineWidth', 1.0);
end
